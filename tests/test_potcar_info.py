"""Tests for POTCAR section parsing (read-only inspection).

The pseudo-hydrogen case is the trap: *_h transition-metal potentials
embed an H PAW dataset INSIDE the element's section — two VRHFIN lines
per section. Element counting must not read that H as structure
hydrogen, and displays flag it.
"""

from vaspen.core.potcar_info import parse_potcar_sections

#: Three sections: plain Fe_pv, plain O, and V_h — the V_h section
#: embeds a pseudo-hydrogen (two VRHFIN lines, two ZVAL numbers).
_POTCAR = """\
  this file is generated by the POTCAR service
    TITEL  = PAW_PBE Fe_pv 06Sep2007
    LULTRA = F
    ZVAL   =  8.000
    ENMAX  = 267.983 eV; the recommended cutoff
    VRHFIN =Fe: 3d64s2
    End of Dataset
    TITEL  = PAW_PBE O 08Apr2002
    ZVAL   =  6.000
    ENMAX  = 400.000 eV
    VRHFIN =O: 2s2 2p4
    End of Dataset
    TITEL  = PAW_PBE V_h 08Apr2002
    ZVAL   =  9.019   1.000
    ENMAX  = 177.443 eV
    VRHFIN =V: 3d34s2
    VRHFIN =H: 1s1
    End of Dataset
"""


def test_parses_sections_with_variant_zval_enmax():
    sections = parse_potcar_sections(_POTCAR)
    assert len(sections) == 3
    assert sections[0]["variant"] == "Fe_pv"
    assert sections[0]["functional"] == "PAW_PBE"
    assert sections[0]["zval"] == 8.0
    assert sections[0]["enmax"] == 267.983
    assert sections[1]["variant"] == "O"
    assert sections[1]["date"] == "08Apr2002"


def test_real_hydrogen_section_is_not_flagged():
    text = """\
    TITEL  = PAW_PBE H 15Jun2001
    ZVAL   =  1.000
    VRHFIN =H: 1s1
    End of Dataset
"""
    (section,) = parse_potcar_sections(text)
    assert section["elements"] == ["H"]
    assert section["pseudo_h"] is False


def test_pseudo_hydrogen_inside_h_variant_is_flagged():
    sections = parse_potcar_sections(_POTCAR)
    v_section = sections[2]
    assert v_section["variant"] == "V_h"
    assert v_section["elements"] == ["V", "H"]
    assert v_section["pseudo_h"] is True
    assert sections[0]["pseudo_h"] is False
    assert sections[1]["pseudo_h"] is False


def test_empty_and_garbage_input():
    assert parse_potcar_sections("") == []
    assert parse_potcar_sections("not a potcar at all") == []


def test_malformed_titel_without_equals_does_not_crash():
    text = "    TITEL  PAW_PBE Fe no equals here\n    End of Dataset\n"
    (section,) = parse_potcar_sections(text)
    assert section["functional"] == "PAW_PBE"
    assert section["variant"] == "Fe"
